#!/usr/bin/env python3
"""MIT. Bind repeat-build bytes and an independent existing esmtool parser."""
from pathlib import Path
import argparse
import datetime
import hashlib
import json
import subprocess
import sys

BASE=Path(__file__).resolve().parent

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def json_write(name, value):
    (BASE/name).write_text(json.dumps(value,indent=2)+'\n',encoding='utf-8')

def generated():
    result={p.relative_to(BASE).as_posix():sha(p) for p in (BASE/'mod').rglob('*') if p.is_file()}
    for name in ('ENTRY.json','HEIGHTFIELD_PREVIEW.png'):
        result[name]=sha(BASE/name)
    return result

def run_source(script, config):
    process=subprocess.run([sys.executable,str(BASE/script),'--base-config',str(config)],
                           check=False,capture_output=True,text=True,timeout=180)
    if process.returncode:
        raise RuntimeError(script+' failed: '+process.stdout+process.stderr)
    print(process.stdout.strip())

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base-config',type=Path,required=True)
    parser.add_argument('--esmtool',type=Path,required=True)
    args=parser.parse_args()
    if not args.esmtool.is_file():
        raise ValueError('Existing official esmtool binary is required')
    tool_binding=json.loads((BASE/'PARSER_BINDING.json').read_text())
    if sha(args.esmtool) != tool_binding['toolSha256']:
        raise ValueError('esmtool binary differs from the reviewed Foundation runtime')
    config_hash=sha(args.base_config)
    for script in ('build-frontier.py','check-frontier.py'):
        run_source(script,args.base_config)
    before=generated()
    for script in ('build-frontier.py','check-frontier.py'):
        run_source(script,args.base_config)
    after=generated()
    if before != after:
        raise ValueError('Generated byte determinism differs')
    if config_hash != sha(args.base_config):
        raise ValueError('Source profile changed')
    now=datetime.datetime.now(datetime.timezone.utc).isoformat()
    json_write('DETERMINISM_RECEIPT.json',{
        'schema':'veyra.frontier-determinism.v1','version':'0.1.0','recordedAt':now,
        'generatorSha256':sha(BASE/'build-frontier.py'),'verifierSha256':sha(Path(__file__)),
        'baseConfigSha256':config_hash,'status':'TWO_BOUND_BUILDS_BYTE_IDENTICAL',
        'rebuildCount':2,'comparedOutputCount':len(after),'outputHashes':after,
        'receiptTimestampsExcluded':True,'nativeEngineStarted':False,
        'claimCeiling':'SAME_BOUND_RUNTIME_AND_INPUTS_GENERATE_SAME_OUTPUT_BYTES'})
    version=subprocess.run([str(args.esmtool),'--version'],capture_output=True,text=True,timeout=30)
    reported_version=(version.stdout+version.stderr).strip()
    # This executable intentionally exits1 after its --version report; that
    # return code is not the parse command's return code.
    if reported_version != tool_binding['reportedVersion'] or version.returncode != tool_binding['versionExitCode']:
        raise ValueError('Expected bound ESMTool format-version report')
    plugin=BASE/'mod/LEVIATH-Frontier.esp'
    result=subprocess.run([str(args.esmtool),'-q','-C','dump',str(plugin)],
                          capture_output=True,text=True,timeout=60)
    public_stdout=result.stdout.replace(str(plugin).replace('\\','\\\\'),'LEVIATH-Frontier.esp').replace(str(plugin),'LEVIATH-Frontier.esp')
    json_write('ESMTOOL_RECEIPT.json',{
        'schema':'veyra.frontier-esmtool.v1','version':'0.1.0','recordedAt':now,
        'toolSha256':sha(args.esmtool),'toolVersion':reported_version,
        'versionReportExitCode':version.returncode,'bindingManifestSha256':sha(BASE/'PARSER_BINDING.json'),
        'pluginSha256':sha(plugin),'commandArguments':['-q','-C','dump','LEVIATH-Frontier.esp'],
        'exitCode':result.returncode,'stdout':public_stdout,'stderr':result.stderr,
        'rawStdoutSha256':hashlib.sha256(result.stdout.encode('utf-8')).hexdigest(),
        'stdoutRedaction':'exact absolute own plugin path replaced by its filename',
        'status':'NATIVE_PARSER_PASS' if result.returncode == 0 else 'NATIVE_PARSER_FAILED',
        'nativeEngineStarted':False,
        'coverage':'TES3 header and record/subrecord acceptance, CELL browsing and WNAM parsing. '
                   'LAND vertex/texture payloads are lazily skipped by this tool; the independent serialized checker covers those bytes.',
        'claimCeiling':'EXISTING_OPENMW_ESMTOOL_RECORD_PARSER_ONLY'})
    if result.returncode:
        raise ValueError('esmtool parser failed; see ESMTOOL_RECEIPT.json')
    print('FRONTIER_VERIFY_PASS rebuildOutputs%d boundESMTool1.3 PASS enginePENDING'%len(after))

if __name__=='__main__':
    main()
